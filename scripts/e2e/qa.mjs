// Free-exploration flow: category -> region -> deploy -> compare numbers -> Gemma plan -> apply -> restore -> reset.
// The Gemma endpoint is stubbed with a saved real response (fixtures/) unless LIVE_PLAN=1.
import { launch, sleep } from './lib.mjs'
const t = await launch()
const { p, check, shot, click, panel, toast, waitFor, api, done, stats } = t
const step = (n) => console.log('\n== ' + n)

await p.goto((process.env.APP_URL ?? 'http://localhost:5173') + '/?shot', { waitUntil: 'networkidle2' }); await sleep(3000)
step('0 first-time welcome')
check('welcome explains the scenario', /A hurricane has hit\. Roads are blocked\. You have limited rescue resources\. Decide where to send them\./.test(await p.evaluate(() => document.querySelector('[aria-label=Welcome]')?.innerText ?? '')))
check('welcome offers demo + explore', await p.evaluate(() => /Start guided demo/.test(document.body.innerText) && /Explore on my own/.test(document.body.innerText)))
await shot('qa_00_welcome')
await click('button', /Explore on my own/)
await p.reload({ waitUntil: 'networkidle2' }); await sleep(2500)
check('welcome not shown again after dismissal (localStorage)', !(await p.evaluate(() => !!document.querySelector('[aria-label=Welcome]'))))
await waitFor(() => /Response zones needing attention/.test(document.querySelector('aside')?.innerText ?? ''), null, 40000); await sleep(2500)

step('1 impact (Cat 3 default)')
check('main nav is exactly Impact | Deploy | Compare', (await p.evaluate(() => [...document.querySelectorAll('[role=tab]')].map((e) => e.textContent.trim()).join('|'))) === 'Impact|Deploy|Compare')
check('Cat 3 selected by default', await p.evaluate(() => document.querySelector('[role=radio][aria-checked=true]')?.textContent === '3'))
const setup = await api('/api/v1/allocation/setup?category=3')
const before = await api('/api/v1/allocation/evaluate', { category: 3, assignments: [] })
let pt = await panel()
check('flooded + debris counts come from API', pt.includes(before.roads.flooded_segments.toLocaleString()) && pt.includes(String(before.roads.debris_total)), `${before.roads.flooded_segments}/${before.roads.debris_total}`)
check('emergency-care card: separate ED / full-service hospital / EMS rows with real denominators', /EMERGENCY CARE ACCESS/i.test(pt) && /verified 24-hour emergency department/.test(pt) && /Full-service hospital/.test(pt) && /EMS teams you send/.test(pt) && /\d[\d,]*\s+of [\d,]+ road-network locations/.test(pt))
const reg = await api('/api/v1/regional-access?category=3'); const edc = reg.results[0].any_24h_ed.local_4km_nodes
check('ED headline equals API (not hardcoded)', pt.replace(/\s+/g, ' ').includes(`${edc.nodes_with_route.toLocaleString()} of ${edc.nodes.toLocaleString()} road-network locations`), `${edc.nodes_with_route}/${edc.nodes}`)
check('source badges present (REAL/CALCULATED/SIMULATED vocabulary)', /CALCULATED/.test(pt) && /SIMULATED/.test(pt))
check('NOAA revision chip in header', /Powered by NOAA Storm-Surge Data/.test(await p.evaluate(() => document.querySelector('header').innerText)) && /6\/18\/2026/.test(await p.evaluate(() => document.querySelector('header').innerText)))
check('tabs live in the right panel (not the global header)', await p.evaluate(() => !!document.querySelector('aside [role=tablist]') && !document.querySelector('header [role=tab]')))
const order = await p.evaluate(() => [...document.querySelectorAll('ol[aria-label^="Response zones"] li button > div:first-child > span:first-child')].map((s) => { const c = s.cloneNode(true); c.querySelectorAll('span').forEach((x) => x.remove()); return c.textContent.trim() }))
check('regions listed in attention_order', order.join('|') === setup.attention_order.map((id) => setup.zones.find((z) => z.zone_id === id).name).join('|'), order.join(', '))
check('no forbidden jargon in the right panel', !/directed edge|marginal|graph node|reachability|bnodes?b/i.test(await p.evaluate(() => document.querySelector('aside').innerText)))
check('disclaimer chip visible', /not for real emergency decisions/i.test(await p.evaluate(() => document.body.innerText)))
const ctaVisible = await p.evaluate(() => { const b = document.querySelector('[data-testid=action-bar] button'); const r = b.getBoundingClientRect(); return r.bottom <= innerHeight && r.top > 0 })
check('sticky action button is always visible', ctaVisible && (await panel()).includes('Select a neighborhood on the map or from the list'))
await shot('qa_01_impact')
for (const k of ['5', '1', '3']) { await p.keyboard.press(k); await sleep(6500) }
check('keys 1-5 change category (3 restored)', await p.evaluate(() => document.querySelector('[role=radio][aria-checked=true]')?.textContent === '3'))
await waitFor(() => /Response zones needing/.test(document.querySelector('aside')?.innerText ?? ''), null, 30000)

step('2 select region (list + map label)')
await click('ol button', /West Augustine/, 1800)
check('list click selects region and CTA names it', /Deploy Resources to West Augustine/.test(await panel()))
check('map region is selected (outline source)', await p.evaluate(() => window.__map.querySourceFeatures('zones').some((f) => f.properties.sel === 1 && f.properties.id === 'west_augustine')))
await shot('qa_02_selected')
await p.evaluate(() => [...document.querySelectorAll('button.maplibregl-marker')].find((e) => /Bridge Corridor/i.test(e.textContent)).click()); await sleep(1500)
check('bridge corridor (no polygon) selectable via its label', /Deploy Resources to Bridge Corridor/.test(await panel()))
await p.evaluate(() => [...document.querySelectorAll('button.maplibregl-marker')].find((e) => /West Augustine/i.test(e.textContent)).click()); await sleep(1500)
await click('[data-testid=action-bar] button', /Deploy Resources to West Augustine/, 800)
check('action button navigates Impact -> Deploy', await p.evaluate(() => document.querySelector('[role=tab][aria-selected=true]')?.textContent === 'Deploy'))

step('3 deploy a debris crew')
pt = await panel()
check('deploy shows region problems', /flooded road segments/.test(pt) && /blocked by debris/.test(pt) && /cut off from help/.test(pt))
check('6 resource rows with +/- and remaining/total', (await p.evaluate(() => document.querySelectorAll('button[aria-label^="Add one"]').length)) === 6 && /Clear Debris\s*2\/2 left/.test(pt))
await shot('qa_03_deploy')
await click('button', /^Add one Debris crew/, 5000)
const ev1 = await api('/api/v1/allocation/evaluate', { category: 3, assignments: [{ resource: 'debris_crew', zone_id: 'west_augustine' }] })
const tm = await toast()
check('toast shows backend message', tm.includes(ev1.assignments[0].message), tm.replace(/\n/g, ' '))
pt = await panel()
const wa = ev1.zones.find((z) => z.zone_id === 'west_augustine')
check('before/after cut-off numbers equal API', new RegExp(`${wa.before.cut_off_locations}\\s*→\\s*${wa.after.cut_off_locations}`).test(pt.replace(/\s+/g, ' ')), `${wa.before.cut_off_locations}->${wa.after.cut_off_locations}`)
check('computed change is real (cut-off decreased)', wa.after.cut_off_locations < wa.before.cut_off_locations)
check('inventory 1/2', /Clear Debris\s*1\/2 left/.test(pt))
check('what improved / still needs help shown', /WHAT IMPROVED\?/i.test(pt) && /WHAT STILL NEEDS HELP\?/i.test(pt) && /Crews cleared:/.test(pt) && /emergency department/.test(pt))
check('cleared roads filter set on map', await p.evaluate(() => JSON.stringify(window.__map.getFilter('cleared-line')).includes('literal') && window.__map.getLayoutProperty('cleared-line', 'visibility') === 'visible'))
await shot('qa_04_crew')

step('4 deploy EMS, compare before/after')
await click('button', /^Add one EMS/, 4500)
const ev2 = await api('/api/v1/allocation/evaluate', { category: 3, assignments: [{ resource: 'debris_crew', zone_id: 'west_augustine' }, { resource: 'ems_team', zone_id: 'west_augustine' }] })
check('EMS toast is backend message', (await toast()).includes(ev2.assignments.find((a) => a.resource === 'ems_team').message))
pt = (await panel()).replace(/\s+/g, ' ')
const wa2 = ev2.zones.find((z) => z.zone_id === 'west_augustine')
check('EMS coverage before->after shown', new RegExp(`EMS coverage 0 → ${wa2.after.ems_locations}`).test(pt), String(wa2.after.ems_locations))
check('EMS overlay auto-enabled with coverage points', await p.evaluate(() => window.__map.getLayoutProperty('cov-ems', 'visibility') === 'visible' && window.__map.querySourceFeatures('cov-ems').length > 0))
await shot('qa_05_ems')

step('5 rejections + inventory limits')
await p.select('select[aria-label=Neighborhood]', 'historic_downtown'); await sleep(1200)
const emsHint = await p.evaluate(() => document.querySelector('button[aria-label^="Add one EMS"]')?.closest('div.rounded-lg')?.innerText ?? '')
check('unavailable action shows backend reason', emsHint.length > 30, emsHint.replace(/\n/g, ' '))
await shot('qa_06_unavailable')
await click('button', /^Add one EMS/, 3500)
const rj = await toast()
check('rejected deployment shows plain message, consumes nothing', rj.length > 5 && /EMS\s*2\/3 left/.test(await panel()), rj.replace(/\n/g, ' '))
await p.select('select[aria-label=Neighborhood]', 'west_augustine'); await sleep(1000)
await click('button', /^Add one Debris crew/, 4500)
const dis = await p.evaluate(() => { const b = document.querySelector('button[aria-label^="Add one Debris crew"]'); return b && { d: b.disabled, t: b.closest('div.rounded-lg')?.innerText } })
check('inventory exhausted disables + with reason', dis?.d === true && /already assigned/.test(dis.t), JSON.stringify(dis))
await click('button', /^Add one EMS/, 4500)
await click('button', /^Add one EMS/, 4500)
check('multiple units of one type in one zone (EMS x2 here), inventory enforced', /Send EMS\s*0\/3 left|Send EMS\s*1\/3 left/.test(await panel()), (await panel()).match(/Send EMS\s*\d\/3 left/)?.[0])

step('6 move + remove')
const n0 = await p.evaluate(() => document.querySelectorAll('select[aria-label^="Move"]').length)
await p.select('select[aria-label^="Move EMS"]', 'lincolnville'); await sleep(3500)
check('move reassigns EMS or explains why not', (await toast()).length > 5, (await toast()).replace(/\n/g, ' '))
await p.evaluate(() => document.querySelector('button[aria-label^="Remove EMS"]')?.click()); await sleep(3500)
check('remove returns unit to inventory', /Send EMS\s*[123]\/3 left/.test(await panel()) && n0 >= 3, 'assigned rows before: ' + n0)
await shot('qa_07_assigned')

const sentLine = await p.evaluate(() => document.querySelector('aside [aria-label="Units used"]').textContent)
step('7 compare + Gemma')
await click('[role=tab]', /Compare/, 800)
check('compare tab: Get AI Recommendation is the sticky primary action', /Get AI Recommendation/.test(await p.evaluate(() => document.querySelector('[data-testid=action-bar]').innerText)))
await click('[data-testid=action-bar] button', /Get AI Recommendation/, 300)
check('progress state while waiting', /Asking Gemma/.test(await panel()))
await waitFor(() => /Real Gemma response|NOT a Gemma/i.test(document.querySelector('aside')?.innerText ?? ''), null, 150000)
pt = await panel()
check('source label is explicit', /Real Gemma response|Deterministic demo fallback — NOT a Gemma response/.test(pt), (pt.match(/Real Gemma response[^\n]*|Deterministic[^\n]*/) || [''])[0])
check('two columns My Response / Gemma', /My Response/i.test(pt) && /Gemma.s Recommendation/i.test(pt))
for (const r of ['Resources used', 'Roads cleared of debris', 'EMS coverage', 'Supply access', 'Potential water rescue', 'Potential helicopter rescue', 'Medical support access']) check('row: ' + r, pt.includes(r))
check('rationale shown per assignment', /Why Gemma chose/.test(pt))
await sleep(1500)
await shot('qa_08_compare')
const mineUsed = await p.evaluate(() => document.querySelector('table[aria-label^="My Response"] tbody tr td:nth-child(2)')?.innerText)
const gemUsed = await p.evaluate(() => document.querySelector('table[aria-label^="My Response"] tbody tr td:nth-child(3)')?.innerText)
console.log('resources used  mine:', mineUsed, ' gemma:', gemUsed)
check('mine column reflects my allocation (units used equals the panel count)', (mineUsed ?? '').startsWith(sentLine.split('/')[0]), `${mineUsed} vs ${sentLine}`)
await click('button', /^Apply Gemma Plan$/, 1500)
check('applying Gemma plan toasts + Restore enabled', /Gemma.s plan is now on the map/.test(await toast()) && await p.evaluate(() => ![...document.querySelectorAll('button')].find((b) => /Restore My Plan/.test(b.textContent)).disabled))
console.log('units after apply:', await p.evaluate(() => document.querySelector('aside [aria-label="Units used"]').textContent))
await shot('qa_09_applied')
await click('button', /^Restore My Plan/, 3500)
check('restore returns my plan (toast)', /Your own plan is restored/.test(await toast()))
check('my units are back', (await panel()).includes(sentLine))
await click('button', /^Reset Allocation/, 3500)
check('reset clears everything', /0\/11 units sent/.test(await panel()))
console.log('plan calls:', stats.planCalls)

step('8 category change clears plan + allocation')
await click('[role=tab]', /Deploy/, 300)
await p.select('select[aria-label=Neighborhood]', 'west_augustine'); await sleep(800)
await click('button', /^Add one Debris crew/, 4000)
await p.keyboard.press('4'); await sleep(7000)
check('cat change resets allocation', /0\/11 units sent/.test(await panel()))
await click('[role=tab]', /Compare/, 500)
check('cat change clears stale plan', !/Real Gemma response/.test(await panel()))

step('9 how it works + layers')
await click('button', /Data and sources/, 500)
const hw = await p.evaluate(() => document.querySelector('[role=dialog]')?.innerText ?? '')
check('data & sources: NOAA revision, classes, separation note, base disclosure, attribution, disclaimer', /NOAA SLOSH MOM v4 — updated 6\/18\/2026/.test(hw) && /not the publication date/.test(hw) && /REAL DATA/.test(hw) && /CALCULATED/.test(hw) && /SIMULATED/.test(hw) && /separate calculations/i.test(hw) && /NetworkX/.test(hw) && /Response base/i.test(hw) && /OpenStreetMap/.test(hw) && /not for real emergency decisions/i.test(hw))
await shot('qa_10_how')
await p.keyboard.press('Escape'); await sleep(300)
const keyN0 = await p.evaluate(() => document.querySelectorAll('[aria-label="Map key"] li').length)
await click('[aria-label="Map key"] button', /All layers/, 400)
const keyN1 = await p.evaluate(() => document.querySelectorAll('[aria-label="Map key"] li').length)
check('map key shows only active layers by default, all 10 entries on request (8 toggles)', keyN0 < keyN1 && keyN1 === 10 && (await p.evaluate(() => document.querySelectorAll('[aria-label="Map key"] input').length)) === 8, `${keyN0} -> ${keyN1}`)
await shot('qa_11_layers')
await done()
