// Guided 5-step demo end to end. Numbers in the coach must come from the API. Gemma is stubbed (fixtures/) unless LIVE_PLAN=1.
import { launch, sleep } from './lib.mjs'
const t = await launch()
const { p, check, shot, click, api, waitFor, done, stats } = t
const coach = () => p.evaluate(() => document.querySelector('[aria-label="Guided demo"]')?.innerText ?? null)
const flat = (s) => (s ?? '').replace(/\s+/g, ' ')
const waitStep = (n, ms = 60000) => waitFor((n) => { const c = document.querySelector('[aria-label="Guided demo"]'); return !!c && c.innerText.includes(`STEP ${n}/5`) && !/Working…/.test(c.innerText) }, n, ms)

await p.goto((process.env.APP_URL ?? 'http://localhost:5173') + '/?shot', { waitUntil: 'networkidle2' }); await sleep(3000)
check('welcome card on first visit shows the NOAA revision', await p.evaluate(() => /Powered by NOAA Storm-Surge Data/.test(document.querySelector('[aria-label=Welcome]')?.innerText ?? '') && /6\/18\/2026/.test(document.querySelector('[aria-label=Welcome]')?.innerText ?? '')))
await shot('demo_0_welcome')
await click('button', /Start guided demo/, 500)
check('welcome dismissed + coach visible', !(await p.evaluate(() => !!document.querySelector('[aria-label=Welcome]'))) && !!(await coach()))
await waitStep(1); await sleep(2500)
const before = await api('/api/v1/allocation/evaluate', { category: 3, assignments: [] })
let c = flat(await coach()); console.log('--- step1:', c.slice(0, 420))
check('step 1: Cat 3 selected', await p.evaluate(() => document.querySelector('[role=radio][aria-checked=true]')?.textContent === '3'))
check('step 1: live flooded + debris numbers', c.includes(before.roads.flooded_segments.toLocaleString()) && c.includes(String(before.roads.debris_total)))
check('step 1: NOAA revision introduced with REAL/CALCULATED/SIMULATED labels', /6\/18\/2026/.test(c) && /REAL DATA/.test(c) && /CALCULATED/.test(c) && /SIMULATED/.test(c))
const reg = await api('/api/v1/regional-access?category=3'); const edc = reg.results[0].any_24h_ed.local_4km_nodes
check('step 1: ED numbers come from the regional API', c.includes(`${edc.nodes_with_route.toLocaleString()} of ${edc.nodes.toLocaleString()}`), `${edc.nodes_with_route}/${edc.nodes}`)
check('step 1: Impact tab active', await p.evaluate(() => document.querySelector('[role=tab][aria-selected=true]')?.textContent === 'Impact'))
await shot('demo_1')

await click('button', /Next/, 500); await waitStep(2); await sleep(2500)
c = flat(await coach()); console.log('--- step2:', c.slice(0, 380))
const setup = await api('/api/v1/allocation/setup?category=3'); const wa = setup.zones.find((z) => z.zone_id === 'west_augustine')
check('step 2: West Augustine selected, live numbers', /West Augustine/.test(c) && c.includes(`${Math.round(wa.cut_off_pct)}%`) && c.includes(`${wa.debris_blocked}`))
check('step 2: Deploy tab shows its problems', await p.evaluate(() => /West Augustine/.test(document.querySelector('select[aria-label=Neighborhood]')?.selectedOptions[0]?.textContent ?? '') && /blocked by debris/.test(document.querySelector('aside').innerText)))
await shot('demo_2')

await click('button', /Next/, 500); await waitStep(3); await sleep(3000)
c = flat(await coach()); console.log('--- step3:', c.slice(0, 380))
const ev = await api('/api/v1/allocation/evaluate', { category: 3, assignments: [{ resource: 'debris_crew', zone_id: 'west_augustine' }] })
check('step 3: coach quotes backend message', c.includes(ev.assignments[0].message), ev.assignments[0].message)
check('step 3: cleared roads drawn', await p.evaluate(() => window.__map.getLayoutProperty('cleared-line', 'visibility') === 'visible' && JSON.stringify(window.__map.getFilter('cleared-line')).includes('literal')))
check('step 3: toast shown', /cleared/.test(await t.toast()))
await shot('demo_3')

await click('button', /Next/, 500); await waitStep(4); await sleep(3500)
c = flat(await coach()); console.log('--- step4:', c.slice(0, 480))
check('step 4: EMS coverage layer on with points', await p.evaluate(() => window.__map.getLayoutProperty('cov-ems', 'visibility') === 'visible' && window.__map.querySourceFeatures('cov-ems').length > 0))
check('step 4: narration has EMS message from API', /EMS team positioned in West Augustine/.test(c))
await shot('demo_4')

await click('button', /Next/, 500)
check('step 5: progress state shown', /Asking Gemma|STEP 5/.test(flat(await coach())))
await waitFor(() => /Real Gemma response|NOT a Gemma/i.test(document.querySelector('[aria-label="Guided demo"]')?.innerText ?? ''), null, 150000)
await sleep(2500)
c = flat(await coach()); console.log('--- step5:', c.slice(0, 480))
check('step 5: source labelled (Gemma vs fallback)', /Real Gemma response|Deterministic demo fallback — NOT a Gemma response/.test(c))
check('step 5: Compare tab with both columns', await p.evaluate(() => document.querySelector('[role=tab][aria-selected=true]')?.textContent === 'Compare' && /Gemma.s Recommendation/i.test(document.querySelector('aside').innerText)))
await shot('demo_5')

await click('button', /Back/, 500); await waitStep(4); check('Back returns to step 4', /STEP 4\/5/.test(await coach()))
await click('button', /Next/, 500); await waitStep(5)
await click('button', /Finish/, 600)
check('Finish closes coach', (await coach()) === null)
check('free exploration afterwards: allocation persists and controls work', /\d\/11 units sent/.test(await p.evaluate(() => document.querySelector('aside').innerText)))
await click('[role=tab]', /Deploy/, 800)
await click('button', /^Add one (Water rescue|Helicopter|Supplies)/, 4500)
check('can still deploy after the demo', /\b[3-9]\/11 units sent/.test(await p.evaluate(() => document.querySelector('aside').innerText)))
console.log('plan calls:', stats.planCalls)
await p.reload({ waitUntil: 'networkidle2' }); await sleep(2500)
check('welcome not shown again after reload', !(await p.evaluate(() => !!document.querySelector('[aria-label=Welcome]'))))
await click('button', /Guided demo/, 500); await waitStep(1, 60000)
check('header button restarts the demo at step 1', /STEP 1\/5/.test(await coach()))
await done()
